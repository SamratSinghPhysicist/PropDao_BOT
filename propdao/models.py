"""
PropDAO Trading Engine - Models & Data Structures
=================================================
Defines core data structures, enums, risk states, trade orders, positions,
and trade outcomes adhering to the PropDAO v1 API reference.
"""

from __future__ import annotations
from dataclasses import dataclass, field
from enum import Enum
from typing import Optional, Dict, Any, List
import time


class OrderDirection(str, Enum):
    LONG = "LONG"
    SHORT = "SHORT"


class OrderSide(str, Enum):
    BUY = "BUY"
    SELL = "SELL"

    @classmethod
    def from_direction(cls, direction: OrderDirection | str) -> OrderSide:
        d = str(direction).upper()
        if "LONG" in d or d == "BUY":
            return cls.BUY
        return cls.SELL

    def to_direction(self) -> OrderDirection:
        return OrderDirection.LONG if self == OrderSide.BUY else OrderDirection.SHORT


class OrderType(str, Enum):
    MARKET = "market"
    LIMIT = "limit"
    STOP_MARKET = "stop_market"
    STOP_LIMIT = "stop_limit"
    TAKE_MARKET = "take_market"
    TAKE_LIMIT = "take_limit"
    SCALE = "scale"
    TWAP = "twap"


class TimeInForce(str, Enum):
    GTC = "gtc"  # Good 'til cancelled (default)
    IOC = "ioc"  # Immediate or cancel (market orders only)
    ALO = "alo"  # Add liquidity only / post-only


class OrderStatus(str, Enum):
    PENDING = "PENDING"
