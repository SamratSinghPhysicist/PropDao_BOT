@dataclass
class Position:
    """An open isolated-margin position on PropDAO."""
    id: str
    symbol: str
    side: OrderSide
    qty: float
    entry: float
    leverage: float
    notional: float
    margin_allocated: float
    opened_at: int
    mark: float
    unrealized_pnl: float
    sl: Optional[float] = None          # Gross USD PnL at trigger or price
    tp: Optional[float] = None          # Gross USD PnL at trigger or price
    sl_price: Optional[float] = None    # Actual stop-loss price
    tp_price: Optional[float] = None    # Actual take-profit price

    @property
    def margin(self) -> float:
        """Alias for margin_allocated or calculated margin collateral."""
        if hasattr(self, "margin_allocated") and self.margin_allocated > 0:
            return self.margin_allocated
        return (self.qty * self.entry) / (self.leverage or 1.0)

    @property
    def liquidation_price(self) -> float:
        """Isolated margin liquidation price: 100 / leverage % adverse move."""
        if self.leverage <= 1.0:
            return 0.0 if self.side == OrderSide.BUY else float("inf")
        pct_move = 1.0 / self.leverage
        if self.side == OrderSide.BUY:
            return max(0.0, self.entry * (1.0 - pct_move))
        else:
            return self.entry * (1.0 + pct_move)


@dataclass
class Order:
    """Resting, triggered, or completed order."""
    id: str
    symbol: str
    side: OrderSide
