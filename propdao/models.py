class FloorKind(str, Enum):
    MAX = "max"          # Static drawdown floor (e.g. 5% below initial balance)
    DAILY = "daily"      # Daily loss limit floor (e.g. 1%, 2% or 3% below 00:00 UTC anchor equity)


