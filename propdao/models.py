@dataclass
class TradeOutcome:
    """Historical completed trade record."""
    trade_id: int | str
    symbol: str
    direction: OrderDirection
    entry_price: float
    exit_price: float
    quantity: float
    leverage: float
    open_time: float
    close_time: float
    realized_pnl_usdc: float
    gross_pnl: float
    fee: float
    open_fee: float = 0.0
    close_fee: float = 0.0
    exit_reason: str = "Manual Close"
    exit_liquidity: str = "taker"
    slippage_pct: float = 0.0
    smc_zone_id: Optional[str] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    @property
    def realized_pnl(self) -> float:
        """Alias for realized_pnl_usdc."""
        return self.realized_pnl_usdc

    @property
    def realized_pnl_usdt(self) -> float:
        """Alias for compatibility with legacy reporting."""
        return self.realized_pnl_usdc

    @property
    def duration_seconds(self) -> float:
        """Duration of trade in seconds."""
        if self.close_time and self.open_time:
            return max(0.0, self.close_time - self.open_time)
        return 0.0

    @property
    def roe_percentage(self) -> float:
        """Return on Equity (Margin) percentage."""
        margin = (self.entry_price * self.quantity) / max(1.0, self.leverage)
        if margin > 0:
            return (self.realized_pnl_usdc / margin) * 100.0
        return 0.0


@dataclass
class AccountState:
    """Full account state representation."""
    account_id: str
    status: AccountStatus
    stage: Stage
    balance: float
    starting_balance: float
    daily_anchor_equity: float
    max_drawdown_limit_pct: float = 5.0
    daily_drawdown_limit_pct: float = 2.0
    profit_target_pct: float = 10.0
    drawdown_breached_at: Optional[int] = None
    open_positions: List[Position] = field(default_factory=list)
    pending_orders: List[Order] = field(default_factory=list)
    twap_orders: List[Dict[str, Any]] = field(default_factory=list)
    trade_history: List[Dict[str, Any]] = field(default_factory=list)
